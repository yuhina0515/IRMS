import docx
import sys

def modify_template(template_path, output_path, weeks_content):
    doc = docx.Document(template_path)
    table = doc.tables[0]
    
    # 填寫週次內容，假設表格的第5到第23行（索引 4 到 22）對應到 1 到 19 週
    for i in range(19):
        row_idx = 4 + i
        # 每週的任務描述填在第3個欄位 (索引 2)
        # 清空原本的內容並填入新內容
        table.rows[row_idx].cells[2].text = weeks_content[i]
        
    doc.save(output_path)
    print(f"Saved to {output_path}")

