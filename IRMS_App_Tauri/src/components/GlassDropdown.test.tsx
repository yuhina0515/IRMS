import { afterEach, describe, expect, it, vi } from 'vitest'
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { GlassDropdown } from './GlassDropdown'
import { pushEscapeHandler, escapeStackDepth } from '../services/escapeStack'

afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.useRealTimers() })
describe('dropdown viewport placement', () => {
  it('opens and navigates by keyboard without committing until Enter', () => {
    const change = vi.fn()
    render(<GlassDropdown value="a" options={[{ value: 'a', label: 'Alpha' }, { value: 'b', label: 'Beta' }]} onChange={change} />)
    const trigger = screen.getByRole('combobox', { name: 'Alpha' })
    trigger.focus()
    fireEvent.keyDown(trigger, { key: 'ArrowDown' })
    expect(screen.getByRole('listbox')).toBeTruthy()
    fireEvent.keyDown(trigger, { key: 'ArrowDown' })
    expect(change).not.toHaveBeenCalled()
    fireEvent.keyDown(trigger, { key: 'Enter' })
    expect(change).toHaveBeenCalledExactlyOnceWith('b')
  })
  it('opens upward at the bottom edge, clamps horizontally and selects an option', () => {
    vi.spyOn(HTMLElement.prototype, 'getBoundingClientRect').mockReturnValue({ top: 730, bottom: 760, left: 970, width: 140, height: 30 } as DOMRect)
    const change = vi.fn()
    render(<GlassDropdown value="a" options={[{ value: 'a', label: 'Alpha' }, { value: 'b', label: 'Beta' }]} onChange={change} />)
    fireEvent.click(screen.getByRole('combobox', { name: /Alpha/ }))
    const popup = screen.getByRole('listbox')
    expect(parseFloat(popup.style.top)).toBeLessThan(730)
    expect(parseFloat(popup.style.left) + parseFloat(popup.style.width)).toBeLessThanOrEqual(window.innerWidth - 8)
    expect(popup.style.overflowY).toBe('auto')
    fireEvent.click(screen.getByRole('option', { name: 'Beta' }))
    expect(change).toHaveBeenCalledWith('b')
  })
  it('repositions on resize and constrains a long list to the available height', () => {
    let bottom = 100
    vi.spyOn(HTMLElement.prototype, 'getBoundingClientRect').mockImplementation(() => ({ top: bottom - 30, bottom, left: 10, width: 200, height: 30 }) as DOMRect)
    render(<GlassDropdown value="0" options={Array.from({ length: 30 }, (_, i) => ({ value: `${i}`, label: `Option ${i}` }))} onChange={() => {}} />)
    fireEvent.click(screen.getByRole('combobox'))
    const popup = screen.getByRole('listbox')
    expect(parseFloat(popup.style.top)).toBe(106)
    bottom = window.innerHeight - 8
    fireEvent.resize(window)
    expect(parseFloat(popup.style.top)).toBeLessThan(bottom - 30)
    expect(parseFloat(popup.style.top) + parseFloat(popup.style.maxHeight)).toBeLessThanOrEqual(window.innerHeight - 8)
  })
})

describe('dropdown keyboard lifecycle', () => {
  const options = [{ value: 'a', label: 'Alpha' }, { value: 'b', label: 'Beta' }, { value: 'c', label: 'Bravo' }]

  it('exposes named relationships, active focus and a single Tab stop', async () => {
    const change = vi.fn()
    render(<><GlassDropdown aria-label="Language" value="a" options={options} onChange={change} /><button>Next</button></>)
    const user = userEvent.setup()
    await user.tab()
    const trigger = screen.getByRole('combobox', { name: 'Language' })
    expect(trigger).toHaveFocus()
    expect(trigger).toHaveAttribute('aria-expanded', 'false')
    await user.keyboard('{ArrowDown}{End}')
    const list = screen.getByRole('listbox', { name: 'Language' })
    expect(trigger).toHaveAttribute('aria-controls', list.id)
    expect(trigger).toHaveAttribute('aria-activedescendant', screen.getByRole('option', { name: 'Bravo' }).id)
    expect(screen.getByRole('option', { name: 'Bravo' })).toHaveAttribute('aria-selected', 'true')
    expect(trigger).toHaveFocus()
    expect(change).not.toHaveBeenCalled()
    await user.tab()
    expect(change).toHaveBeenCalledExactlyOnceWith('c')
    expect(screen.getByRole('button', { name: 'Next' })).toHaveFocus()
    expect(trigger).toHaveAttribute('aria-expanded', 'false')
    expect(trigger).not.toHaveAttribute('aria-activedescendant')
    expect(screen.queryByRole('listbox')).not.toBeInTheDocument()
    expect(list).toHaveAttribute('aria-hidden', 'true')
    fireEvent.click(list.querySelector('[role=option]')!)
    expect(change).toHaveBeenCalledTimes(1)
  })

  it('Escape cancels only this layer through the closing animation', () => {
    vi.useFakeTimers()
    const parent = vi.fn()
    const removeParent = pushEscapeHandler(parent)
    const change = vi.fn()
    const { unmount } = render(<GlassDropdown value="a" options={options} onChange={change} />)
    const trigger = screen.getByRole('combobox')
    trigger.focus()
    fireEvent.keyDown(trigger, { key: 'End' })
    fireEvent.keyDown(trigger, { key: 'Escape' })
    expect(change).not.toHaveBeenCalled()
    expect(trigger).toHaveTextContent('Alpha')
    expect(trigger).toHaveFocus()
    fireEvent.keyDown(trigger, { key: 'Escape' })
    expect(parent).not.toHaveBeenCalled()
    act(() => vi.advanceTimersByTime(100))
    fireEvent.keyDown(trigger, { key: 'Escape' })
    expect(parent).toHaveBeenCalledTimes(1)
    unmount(); removeParent()
    expect(escapeStackDepth()).toBe(0)
  })

  it('supports Home/End, bounded arrows, prefix search and repeated-character cycling', async () => {
    const change = vi.fn()
    render(<GlassDropdown value="a" options={options} onChange={change} />)
    const trigger = screen.getByRole('combobox')
    trigger.focus()
    const user = userEvent.setup()
    await user.keyboard('b')
    expect(trigger).toHaveAttribute('aria-activedescendant', screen.getByRole('option', { name: 'Beta' }).id)
    await user.keyboard('b')
    expect(trigger).toHaveAttribute('aria-activedescendant', screen.getByRole('option', { name: 'Bravo' }).id)
    await user.keyboard('{Home}{ArrowUp}')
    expect(trigger).toHaveAttribute('aria-activedescendant', screen.getByRole('option', { name: 'Alpha' }).id)
    await user.keyboard('{End}{ArrowDown}{Enter}')
    expect(change).toHaveBeenCalledExactlyOnceWith('c')
    expect(trigger).toHaveFocus()
  })

  it('reconciles reordered/removed choices and does not resurrect a disabled popup', () => {
    const change = vi.fn()
    const { rerender } = render(<GlassDropdown value="a" options={options} onChange={change} />)
    const trigger = screen.getByRole('combobox')
    fireEvent.keyDown(trigger, { key: 'End' })
    rerender(<GlassDropdown value="a" options={[options[2], options[0]]} onChange={change} />)
    expect(trigger).toHaveAttribute('aria-activedescendant', screen.getByRole('option', { name: 'Bravo' }).id)
    rerender(<GlassDropdown value="a" options={[options[0]]} onChange={change} />)
    expect(trigger).toHaveAttribute('aria-activedescendant', screen.getByRole('option', { name: 'Alpha' }).id)
    rerender(<GlassDropdown value="a" options={options} onChange={change} disabled />)
    expect(screen.queryByRole('listbox')).not.toBeInTheDocument()
    rerender(<GlassDropdown value="a" options={options} onChange={change} />)
    expect(trigger).toHaveAttribute('aria-expanded', 'false')
    fireEvent.keyDown(trigger, { key: 'ArrowDown' })
    expect(trigger).toHaveAttribute('aria-activedescendant', screen.getByRole('option', { name: 'Alpha' }).id)
    expect(change).not.toHaveBeenCalled()
  })

  it('empty lists, composing keys and rapid reopen cannot commit stale choices', () => {
    vi.useFakeTimers()
    const change = vi.fn()
    const { rerender } = render(<GlassDropdown value="a" options={[]} onChange={change} />)
    const trigger = screen.getByRole('combobox')
    fireEvent.keyDown(trigger, { key: 'ArrowDown', isComposing: true })
    expect(trigger).toHaveAttribute('aria-expanded', 'false')
    fireEvent.keyDown(trigger, { key: 'ArrowDown' })
    expect(trigger).not.toHaveAttribute('aria-activedescendant')
    fireEvent.keyDown(trigger, { key: 'Enter' })
    expect(change).not.toHaveBeenCalled()
    rerender(<GlassDropdown value="a" options={options} onChange={change} />)
    fireEvent.keyDown(trigger, { key: 'ArrowDown' })
    act(() => vi.advanceTimersByTime(100))
    expect(screen.getByRole('listbox')).toBeInTheDocument()
    fireEvent.keyDown(trigger, { key: ' ' })
    expect(change).toHaveBeenCalledExactlyOnceWith('a')
  })
})
